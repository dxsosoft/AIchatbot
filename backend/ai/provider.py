"""
Configurable AI Model Provider Interface.
Supports Google Gemini, OpenAI, Mock/Test provider, and provides clear configuration
errors when credentials are missing (never returns fake answers).
"""

from abc import ABC, abstractmethod
from typing import Optional
from backend.config import (
    AI_PROVIDER,
    AI_MODEL_NAME,
    GEMINI_API_KEY,
    OPENAI_API_KEY,
)


class AIProviderError(Exception):
    """Base exception for AI provider operations."""
    pass


class AIConfigurationError(AIProviderError):
    """Raised when required AI credentials or model configurations are missing."""
    pass


class BaseAIProvider(ABC):
    """Abstract interface for LLM providers."""

    @property
    @abstractmethod
    def name(self) -> str:
        """Name of the active provider."""
        pass

    @abstractmethod
    def generate(self, prompt: str, system_instruction: str) -> str:
        """Generates grounded answer from prompt and system instructions."""
        pass


class GeminiProvider(BaseAIProvider):
    """Google Gemini model provider using official google-genai SDK."""

    def __init__(self, api_key: str, model_name: str = AI_MODEL_NAME):
        if not api_key:
            raise AIConfigurationError(
                "GEMINI_API_KEY is not set. Please provide your Google Gemini API key in the .env file."
            )
        self.api_key = api_key
        self.model_name = model_name
        try:
            from google import genai
            self.client = genai.Client(api_key=self.api_key)
        except Exception as e:
            raise AIProviderError(f"Failed to initialize Google Gemini client: {str(e)}")

    @property
    def name(self) -> str:
        return f"Gemini ({self.model_name})"

    def generate(self, prompt: str, system_instruction: str) -> str:
        try:
            response = self.client.models.generate_content(
                model=self.model_name,
                contents=prompt,
                config={
                    "system_instruction": system_instruction,
                    "temperature": 0.2,
                }
            )
            return response.text.strip() if response.text else "No response generated by model."
        except Exception as e:
            raise AIProviderError(f"Gemini API error during generation: {str(e)}")


class OpenAIProvider(BaseAIProvider):
    """OpenAI model provider using official openai SDK."""

    def __init__(self, api_key: str, model_name: str = "gpt-4o-mini"):
        if not api_key:
            raise AIConfigurationError(
                "OPENAI_API_KEY is not set. Please provide your OpenAI API key in the .env file."
            )
        self.api_key = api_key
        self.model_name = model_name
        try:
            from openai import OpenAI
            self.client = OpenAI(api_key=self.api_key)
        except Exception as e:
            raise AIProviderError(f"Failed to initialize OpenAI client: {str(e)}")

    @property
    def name(self) -> str:
        return f"OpenAI ({self.model_name})"

    def generate(self, prompt: str, system_instruction: str) -> str:
        try:
            response = self.client.chat.completions.create(
                model=self.model_name,
                messages=[
                    {"role": "system", "content": system_instruction},
                    {"role": "user", "content": prompt}
                ],
                temperature=0.2
            )
            return response.choices[0].message.content.strip()
        except Exception as e:
            raise AIProviderError(f"OpenAI API error during generation: {str(e)}")


class MockProvider(BaseAIProvider):
    """Deterministic offline provider for automated testing and CI verification."""

    def __init__(self, model_name: str = "offline-mock"):
        self.model_name = model_name

    @property
    def name(self) -> str:
        return f"MockProvider ({self.model_name})"

    def generate(self, prompt: str, system_instruction: str) -> str:
        # Deterministically extract relevant lines from the prompt context
        lines = prompt.splitlines()
        excerpt_lines = []
        is_in_excerpt = False

        for line in lines:
            if "--- EXCERPT" in line:
                is_in_excerpt = True
                continue
            elif "--- END EXCERPT" in line:
                is_in_excerpt = False
                continue

            if is_in_excerpt and line.strip() and not line.startswith("Columns:"):
                excerpt_lines.append(line.strip())

        if not excerpt_lines:
            return "The provided documents do not contain information to answer this question."

        # Return a synthesized summary directly from the excerpts
        sample_fact = excerpt_lines[0]
        return (
            f"Based on the provided documents:\n\n"
            f"- {sample_fact}\n\n"
            f"(Verified via offline test model grounding)"
        )


class ConfigErrorProvider(BaseAIProvider):
    """Used when no provider credentials have been configured."""

    @property
    def name(self) -> str:
        return "unconfigured"

    def generate(self, prompt: str, system_instruction: str) -> str:
        raise AIConfigurationError(
            "AI Provider is not configured. Please configure an API key in your .env file "
            "(e.g., GEMINI_API_KEY=your_key or OPENAI_API_KEY=your_key) to enable question answering."
        )


def get_ai_provider(provider_name: Optional[str] = None) -> BaseAIProvider:
    """
    Factory function to select and instantiate the appropriate AI Provider.
    Does not hardcode keys or assume a final choice.
    """
    chosen = (provider_name or AI_PROVIDER or "").strip().lower()

    if chosen == "mock":
        return MockProvider()

    if chosen == "gemini" or (not chosen and GEMINI_API_KEY):
        if not GEMINI_API_KEY:
            return ConfigErrorProvider()
        return GeminiProvider(api_key=GEMINI_API_KEY)

    if chosen == "openai" or (not chosen and OPENAI_API_KEY):
        if not OPENAI_API_KEY:
            return ConfigErrorProvider()
        return OpenAIProvider(api_key=OPENAI_API_KEY)

    return ConfigErrorProvider()
